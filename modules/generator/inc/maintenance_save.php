<?php
function createIndex() {
	global $site_default, $db;
	?>
<!DOCTYPE html>
<html>
	<head>
			
		<meta charset="UTF-8">
		<meta name="description" content="Rallye mathématique romand - concours mathématique pour les classes de la scolarité obligatoire">
		<meta name="keywords" content="math, mathématiques, concours">
		<meta name="author" content="Association du rallye mathématique romand">

		<link href="https://cdn.jsdelivr.net/npm/quill@2.0.2/dist/quill.snow.css" rel="stylesheet">
		<link rel="icon" type="image/x-icon" href="/img/favicon.ico">
		<title><?php echo $site_default['site_title']; ?></title>
		<link href="css/labo_basis.css?a=0" rel="stylesheet">
		<link href="css/main.css?a=0" rel="stylesheet">
		<link rel="preconnect" href="https://fonts.googleapis.com">
		<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
		<link href="https://fonts.googleapis.com/css2?family=Arimo:ital,wght@0,400..700;1,400..700&display=swap" rel="stylesheet">
	</head>
	<body>
		<header class= horizontal>
			<a class="site_name" href="/">
<?php
		echo $site_default['html_content_for_site_name'];		
?>
			</a>
			<div class="menu_hidder">
				<img src="icons/menu_white.svg" />
			</div>
			<menu class="vertical"></menu>
		</header>
		<content>
<?php
	// get now all post for getted page
	// get all posts
	$d_posts = $db->prepare('
		SELECT * FROM posts AS po
		INNER JOIN pages AS pa
		ON pa.id = po.page_id
		WHERE page_slug = :ps AND
			po.logical_delete <> 1
		ORDER BY position_on_page');
	$d_posts->execute(array('ps' => 'accueil'));
	$posts = $d_posts->fetchAll();

	// display posts
	foreach($posts as $p) {
		echo '<div class="ql-editor post_' . $p['background_color'] . '">'. $p['content'] . '</div>';
	}
?>
		</content>
<?php
	// note that html sended page body and html are not closed to add splash generated by index.php for the differents users
	return;
}

// get site default and write in it state of maintenance (remove or add line maintenance)
$site_default = false;
if (is_file('../default/site_default.json')) {
	$site_default = json_decode(file_get_contents('../default/site_default.json'), true);
} else if (is_file('../default/default.json')) {
	$site_default = json_decode(file_get_contents('../default/default.json'), true);
} else {
	exit('ko-default file missing');
}

if (isset($_POST['maintenance_on'])) {
	if ($_POST['maintenance_on'] == 1) {
		$site_default['maintenance'] = array(
			"maintenance_mode" => "on",
		);
		if (isset($_POST['with_login']) && $_POST['with_login'] == 1) {
			$site_default['maintenance']['login'] = 'on';
			$site_default['maintenance']['login_for'] = htmlspecialchars($_POST['connection_for']);
		}

		// create html page and add splash
		ob_start();
		createIndex();
		
		$maintenance_content = ob_get_contents();
		ob_end_clean();
		file_put_contents('../default/site_maintenance.html', $maintenance_content);

		$return_string = 'file_writen';
	} else if ($_POST['maintenance_on'] == 0) {
		unset($site_default['maintenance']);
		unlink('../default/site_maintenance.html');
	}

	// change site_default.json
	file_put_contents('../default/site_default.json', json_encode($site_default));
}